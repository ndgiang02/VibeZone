using System.Security.Cryptography;
using System.Text;

namespace VibeZone.Modules.Analytics.Domain;

public enum PlayEventType
{
    Started,
    Progress,
    Completed,
}

/// <summary>
/// The valid-listen rule (data-model.md): at least 30 s of actual playback, or half of a track shorter than
/// 60 s; at most one valid listen per listener and track per 30 minutes.
/// </summary>
public static class ValidListenRule
{
    public static readonly TimeSpan DedupeWindow = TimeSpan.FromMinutes(30);

    /// <summary>Reported listening may run ahead of wall-clock time by at most this much (clock skew, batching).</summary>
    public static readonly TimeSpan Slack = TimeSpan.FromSeconds(10);

    public static int ThresholdMs(int? durationMs) => durationMs is { } d && d < 60_000 ? Math.Max(d / 2, 1) : 30_000;

    /// <summary>
    /// Who listened, for de-duplication: the account, else a hash of the browser's anonymous client id, else the
    /// playback session itself. The raw client id is never stored.
    /// </summary>
    public static string ListenerKey(Guid? userId, Guid? clientId, Guid sessionId) =>
        userId is { } u ? $"u:{u:N}"
        : clientId is { } c ? "a:" + Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(c.ToString("N"))))[..32]
        : $"s:{sessionId:N}";
}

/// <summary>One event from a player. <see cref="Id"/> is generated by the client: re-sending is a no-op.</summary>
public sealed class PlayEvent
{
    private PlayEvent() { }

    public PlayEvent(Guid id, Guid sessionId, Guid? userId, Guid trackId, PlayEventType type, int positionMs, int listenedMs, DateTimeOffset? clientTimestamp, DateTimeOffset receivedAt)
    {
        Id = id;
        SessionId = sessionId;
        UserId = userId;
        TrackId = trackId;
        Type = type;
        PositionMs = positionMs;
        ListenedMs = listenedMs;
        ClientTimestamp = clientTimestamp;
        ReceivedAt = receivedAt;
    }

    public Guid Id { get; private set; }

    public Guid SessionId { get; private set; }

    public Guid? UserId { get; private set; }

    public Guid TrackId { get; private set; }

    public PlayEventType Type { get; private set; }

    public int PositionMs { get; private set; }

    /// <summary>Playback time the client accumulated in this session so far (not the position: seeks don't count).</summary>
    public int ListenedMs { get; private set; }

    public DateTimeOffset? ClientTimestamp { get; private set; }

    public DateTimeOffset ReceivedAt { get; private set; }
}

/// <summary>
/// One playback of one track by one listener (a row of listening history). Listening time is the client's
/// report, capped by the wall-clock time since the session started so it can't be inflated.
/// </summary>
public sealed class PlaySession
{
    public const int MaxListenerKeyLength = 40;

    private PlaySession() { }

    public static PlaySession Start(Guid sessionId, string listenerKey, Guid? userId, Guid trackId, DateTimeOffset now) => new()
    {
        Id = sessionId,
        ListenerKey = listenerKey,
        UserId = userId,
        TrackId = trackId,
        StartedAt = now,
        LastEventAt = now,
    };

    public Guid Id { get; private set; }

    public string ListenerKey { get; private set; } = string.Empty;

    public Guid? UserId { get; private set; }

    public Guid TrackId { get; private set; }

    public DateTimeOffset StartedAt { get; private set; }

    public DateTimeOffset LastEventAt { get; private set; }

    public int ListenedMs { get; private set; }

    public bool IsValidListen { get; private set; }

    public DateTimeOffset? ValidAt { get; private set; }

    public bool BelongsTo(string listenerKey, Guid trackId) => ListenerKey == listenerKey && TrackId == trackId;

    public void RecordProgress(int reportedListenedMs, DateTimeOffset now)
    {
        var cap = (long)(now - StartedAt + ValidListenRule.Slack).TotalMilliseconds;
        var listened = (int)Math.Clamp(reportedListenedMs, 0, Math.Min(cap, int.MaxValue));
        ListenedMs = Math.Max(ListenedMs, listened);
        LastEventAt = now;
    }

    public bool ReachedThreshold(int? trackDurationMs) => ListenedMs >= ValidListenRule.ThresholdMs(trackDurationMs);

    public void MarkValid(DateTimeOffset now)
    {
        IsValidListen = true;
        ValidAt = now;
    }
}

/// <summary>Per-track, per-day (UTC) counters that drive trending and play counts.</summary>
public sealed class TrackDailyStat
{
    private TrackDailyStat() { }

    public TrackDailyStat(Guid trackId, DateOnly day)
    {
        TrackId = trackId;
        Day = day;
    }

    public Guid TrackId { get; private set; }

    public DateOnly Day { get; private set; }

    /// <summary>Playback sessions started.</summary>
    public int Plays { get; private set; }

    public int ValidListens { get; private set; }

    /// <summary>Likes given that day (unlikes are not subtracted).</summary>
    public int Likes { get; private set; }

    public void AddLike() => Likes++;
}
